import type { ComponentType, NodeConfig } from './types';

export interface ConfigField {
  key: string;
  label: string;
  kind: 'select' | 'range' | 'toggle';
  options?: { value: string; label: string }[];
  min?: number;
  max?: number;
  step?: number;
  help: string;
}

